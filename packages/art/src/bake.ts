// Renders every pose x skin: SVGs for the web, 1-bit bitmaps for the device
// (a C header the firmware includes), a contact sheet, and a side-by-side
// with the reference to review them.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { Resvg } from '@resvg/resvg-js';
import { EXPRESSIONS, POSES, SKINS, SIZE, bust, compose, type Pose, type Skin } from './rig.ts';
import { cArray, packBits } from './bitmap.ts';
import { pose, type Pose as BodyPose } from './body.ts';
import { svg as frame, DEVICE_PALETTE } from './rig.ts';

const root = resolve(import.meta.dirname, '..');
const out = resolve(root, 'out');
const header = resolve(root, '../firmware/include/art/kaelthos.h');
mkdirSync(out, { recursive: true });
mkdirSync(resolve(header, '..'), { recursive: true });

// Device sizes: the WAKING portrait fills the screen; the running-session
// figure shares it with text.
const DEVICE_SIZES: Record<Pose, number> = { idle: 200, focused: 120 };

// No anti-aliasing: the render is already 1-bit, so the preview is exactly
// what the panel shows.
function render(svg: string, width: number, crisp: boolean) {
  return new Resvg(svg, {
    fitTo: { mode: 'width', value: width },
    shapeRendering: crisp ? 0 : 2,
  }).render();
}

const cName = (pose: Pose, skin: Skin) => `KAELTHOS_${pose.toUpperCase()}_${skin.toUpperCase()}`;
const arrays: string[] = [];
const tiles: string[] = [];

for (const [row, pose] of POSES.entries()) {
  for (const [col, skin] of SKINS.entries()) {
    const svg = compose(pose, skin);
    writeFileSync(resolve(out, `${pose}-${skin}.svg`), svg);

    const size = DEVICE_SIZES[pose];
    const device = render(svg, size, true);
    arrays.push(cArray(cName(pose, skin), size, size, packBits(device.pixels, size, size)));

    // Sheet: smooth render, then the device render at 2x beside it.
    const x = col * 2 * (SIZE + 20);
    const y = row * (SIZE + 20);
    const png = (buf: Buffer) => `data:image/png;base64,${buf.toString('base64')}`;
    tiles.push(`<image x="${x}" y="${y}" width="${SIZE}" height="${SIZE}" href="${png(render(svg, SIZE, false).asPng())}"/>`);
    tiles.push(`<image x="${x + SIZE + 10}" y="${y}" width="${size * 2}" height="${size * 2}" style="image-rendering:pixelated" href="${png(device.asPng())}"/>`);
  }
}

writeFileSync(header, [
  '#pragma once',
  '// Generated by packages/art (pnpm --filter @aura/art bake). Do not edit.',
  '#include <stdint.h>',
  '#ifndef PROGMEM',
  '#define PROGMEM',
  '#endif',
  '',
  ...arrays,
  '',
].join('\n'));

const sheetW = SKINS.length * 2 * (SIZE + 20);
const sheetH = POSES.length * (SIZE + 20);
const sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="${sheetW}" height="${sheetH}"><rect width="100%" height="100%" fill="#888"/>${tiles.join('')}</svg>`;
writeFileSync(resolve(out, 'sheet.png'), new Resvg(sheet).render().asPng());

// The style check: the reference beside idle and focused (see STYLE.md).
const reference = readFileSync(resolve(root, '../../inspiration/reference-jiji.png')).toString('base64');
const smooth = (pose: Pose) => render(compose(pose, 'default'), SIZE, false).asPng().toString('base64');
const compare = `<svg xmlns="http://www.w3.org/2000/svg" width="1240" height="420"><rect width="100%" height="100%" fill="#fff"/>`
  + `<image width="400" height="420" href="data:image/png;base64,${reference}"/>`
  + `<image x="420" y="10" width="400" height="400" href="data:image/png;base64,${smooth('idle')}"/>`
  + `<image x="840" y="10" width="400" height="400" href="data:image/png;base64,${smooth('focused')}"/></svg>`;
writeFileSync(resolve(out, 'compare.png'), new Resvg(compare).render().asPng());
console.log(`baked ${POSES.length * SKINS.length} frames -> ${header}`);

// The face kit: every named expression, smooth beside the device's 1-bit
// render at its real 200 px, labelled.
const names = Object.keys(EXPRESSIONS) as (keyof typeof EXPRESSIONS)[];
const COLS = 4;
const TILE_W = 430;
const TILE_H = 240;
const faces = names.map((name, i) => {
  const x = (i % COLS) * TILE_W;
  const y = Math.floor(i / COLS) * TILE_H;
  const art = bust(EXPRESSIONS[name]);
  const png = (buf: Buffer) => `data:image/png;base64,${buf.toString('base64')}`;
  return `<image x="${x}" y="${y + 30}" width="200" height="200" href="${png(render(art, 200, false).asPng())}"/>`
    + `<image x="${x + 210}" y="${y + 30}" width="200" height="200" href="${png(render(art, 200, true).asPng())}"/>`
    + `<text x="${x + 4}" y="${y + 22}" font-family="Consolas, monospace" font-size="20">${name}</text>`;
});
const sheetFaces = `<svg xmlns="http://www.w3.org/2000/svg" width="${COLS * TILE_W}" height="${Math.ceil(names.length / COLS) * TILE_H}">`
  + `<rect width="100%" height="100%" fill="#ddd"/>${faces.join('')}</svg>`;
writeFileSync(resolve(out, 'expressions.png'), new Resvg(sheetFaces).render().asPng());

// The body kit: each pose with a fitting face, smooth beside the device render.
const POSE_FACES: [BodyPose, keyof typeof EXPRESSIONS][] = [
  ['sit', 'curious'], ['back', 'curious'], ['wave', 'happy'], ['loaf', 'asleep'], ['peek', 'curious'],
];
const poseTiles = POSE_FACES.map(([kind, face], i) => {
  const x = (i % COLS) * TILE_W;
  const y = Math.floor(i / COLS) * TILE_H;
  const art = frame(pose(kind, EXPRESSIONS[face], DEVICE_PALETTE), DEVICE_PALETTE);
  const png = (buf: Buffer) => `data:image/png;base64,${buf.toString('base64')}`;
  return `<image x="${x}" y="${y + 30}" width="200" height="200" href="${png(render(art, 200, false).asPng())}"/>`
    + `<image x="${x + 210}" y="${y + 30}" width="200" height="200" href="${png(render(art, 200, true).asPng())}"/>`
    + `<text x="${x + 4}" y="${y + 22}" font-family="Consolas, monospace" font-size="20">${kind} / ${face}</text>`;
});
writeFileSync(resolve(out, 'poses.png'), new Resvg(`<svg xmlns="http://www.w3.org/2000/svg" width="${COLS * TILE_W}" height="${Math.ceil(POSE_FACES.length / COLS) * TILE_H}"><rect width="100%" height="100%" fill="#ddd"/>${poseTiles.join('')}</svg>`).render().asPng());
